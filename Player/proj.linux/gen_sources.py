#!/usr/bin/env python3
"""Generate proj.linux/sources.cmake from the Visual Studio projects.

The Windows projects are the authoritative source lists for the player. This
script reads them and maps the Windows-only files to their Linux counterparts,
so that the Linux build follows upstream changes by re-running it:

    python3 proj.linux/gen_sources.py
"""

import os
import sys
import xml.etree.ElementTree as ET

MSBUILD_NS = '{http://schemas.microsoft.com/developer/msbuild/2003}'

PLAYER_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

PROJECTS = {
    'PGMMV_PLAYER_SOURCES': 'proj.win32/player.vcxproj',
    'PGMMV_COCOS_SOURCES': 'cocos2d/cocos/2d/libcocos2d.vcxproj',
    'PGMMV_JSB_SOURCES': 'cocos2d/cocos/scripting/js-bindings/proj.win32/libjscocos2d.vcxproj',
    'PGMMV_RECAST_SOURCES': 'cocos2d/external/recast/proj.win32/librecast.vcxproj',
    'PGMMV_CHIPMUNK_SOURCES': 'cocos2d/external/win32-specific/chipmunk/libchipmunk/libchipmunk/libchipmunk.vcxproj',
}

# Windows-only files with no Linux counterpart, or replaced by files in proj.linux.
DROPPED = {
    'proj.win32/main.cpp',
    'proj.win32/stdafx.cpp',
    'proj.win32/DllPluginManager-win32.cpp',
    'cocos2d/cocos/platform/win32/CCUtils-win32.cpp',
    'cocos2d/cocos/audio/win32/MciPlayer.cpp',
    'cocos2d/cocos/audio/win32/SimpleAudioEngine.cpp',
}

# Files added to the Linux build in place of dropped ones.
ADDED = {
    'PGMMV_PLAYER_SOURCES': [
        'proj.linux/main.cpp',
        'proj.linux/LinuxPlatform.cpp',
        'proj.linux/DllPluginManager-linux.cpp',
        'proj.linux/LibVlcLoader.cpp',
    ],
    'PGMMV_COCOS_SOURCES': [
        'proj.linux/engine/SimpleAudioEngine-linux.cpp',
    ],
}


# Directories whose *-win32.cpp files are replaced by the *-linux.cpp ones.
# audio/win32 is kept: it is the OpenAL backend the AGTK patches target.
MAPPED_DIRS = ('cocos2d/cocos/platform/win32/', 'cocos2d/cocos/ui/UIEditBox/')


def linux_counterpart(path):
    """Map Foo-win32.cpp to Foo-linux.cpp (platform/win32 files live in platform/linux)."""
    if not path.startswith(MAPPED_DIRS) or not path.endswith('-win32.cpp'):
        return path
    candidate = path.replace('/platform/win32/', '/platform/linux/')
    candidate = candidate[:-len('-win32.cpp')] + '-linux.cpp'
    if not os.path.exists(os.path.join(PLAYER_DIR, candidate)):
        sys.exit('no Linux counterpart for ' + path)
    return candidate


def project_sources(project):
    project_path = os.path.join(PLAYER_DIR, project)
    project_dir = os.path.dirname(project_path)
    root = ET.parse(project_path).getroot()
    sources = []
    for item in root.iter(MSBUILD_NS + 'ClCompile'):
        include = item.get('Include')
        if not include:
            continue
        excluded = [child for child in item
                    if child.tag == MSBUILD_NS + 'ExcludedFromBuild'
                    and (child.text or '').strip().lower() == 'true']
        if excluded:
            continue
        full = os.path.normpath(os.path.join(project_dir, include.replace('\\', '/')))
        path = os.path.relpath(full, PLAYER_DIR)
        if path in DROPPED:
            continue
        path = linux_counterpart(path)
        if not os.path.exists(os.path.join(PLAYER_DIR, path)):
            sys.exit('missing source listed in %s: %s' % (project, path))
        sources.append(path)
    return sources


def main():
    out = ['# Generated by proj.linux/gen_sources.py from the Visual Studio projects. Do not edit.', '']
    for var, project in PROJECTS.items():
        sources = project_sources(project) + ADDED.get(var, [])
        out.append('set(%s' % var)
        out.extend('    ' + s for s in sources)
        out.append(')')
        out.append('')
    with open(os.path.join(PLAYER_DIR, 'proj.linux', 'sources.cmake'), 'w') as f:
        f.write('\n'.join(out))


if __name__ == '__main__':
    main()
